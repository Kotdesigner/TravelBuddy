// Kamerafahrt: Verkehrsmittel, Zoom im Verhältnis zur Strecke, erst langsam, dann schnell.
import assert from 'node:assert/strict'
import { artDerTour, verlauf, punktBei, spitzenZoom, anzoom, zoomBei, dauerFuer, NAH_ZOOM } from '../src/lib/reisefahrt.js'

assert.equal(artDerTour({ art: 'flug' }), 'flug')
assert.equal(artDerTour({ art: 'bahn', route: { flug: true } }), 'bahn')
assert.equal(artDerTour({ art: 'boot', route: { flug: true } }), 'boot')
assert.equal(artDerTour({ name: 'Fähre nach Rottnest' }), 'boot')
assert.equal(artDerTour({ name: 'Coral Coast' }), 'auto')
assert.equal(artDerTour({ route: { flug: true }, name: 'Ferry' }), 'flug')
const v = verlauf([[115.86, -31.95], [116.86, -31.95]])
assert.ok(v.gesamt > 90 && v.gesamt < 100)
assert.ok(Math.abs(punktBei(v, 0.5).lon - 116.36) < 0.01)
assert.ok(Math.abs(punktBei(v, 0.5).richtung - 90) < 1)
const kurz = spitzenZoom(20), mittel = spitzenZoom(300), lang = spitzenZoom(16000)
assert.ok(kurz > mittel && mittel > lang, [kurz, mittel, lang].join())
assert.ok(mittel > 5 && lang < 3)
assert.ok(spitzenZoom(2) <= NAH_ZOOM)
assert.ok(anzoom(0.5) < 0.2 && anzoom(1) === 1)
assert.equal(zoomBei(0, 11, 5), 11)
assert.equal(Math.round(zoomBei(0.5, 11, 5)), 5)
assert.ok(dauerFuer(16000) > dauerFuer(20) && dauerFuer(1e7) <= 8)
const { zieleVon, streckeText } = await import('../src/lib/plan.js')
assert.equal(streckeText({ ort: 'A', ziele: [{ name: 'B' }, { name: 'C' }] }), 'A → B → C')
assert.equal(streckeText({ ort: 'A', ziel: { name: 'B' } }), 'A → B')
assert.equal(streckeText({ ort: 'A' }), 'A')
assert.equal(zieleVon({}).length, 0)
const { logbuchTouren, artDesTages, tagesPunkte } = await import('../src/lib/reisefahrt.js')
const tag = { id: 'a', datum: '2030-05-02', ort: 'Exmouth', lat: -22, lon: 114, imFilm: true, ziele: [{ name: 'Coral Bay', lat: -23, lon: 113.8 }], felder: { verkehrsmittel: ['🚤 Boot'] } }
assert.equal(artDesTages(tag), 'boot')
assert.equal(logbuchTouren([tag])[0].name, 'Exmouth → Coral Bay')
assert.equal(logbuchTouren([tag])[0].art, 'boot')
assert.equal(logbuchTouren([{ ...tag, imFilm: false }]).length, 0)
assert.equal(tagesPunkte({ ...tag, ziele: [{ name: 'X' }] }).vollstaendig, false)
console.log('✓ Reisefahrt')
